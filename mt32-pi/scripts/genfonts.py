#!/usr/bin/env python3
#
# genfonts.py
#
# Generates src/lcd/fonts.cpp: anti-aliased bitmap fonts (4 bits per pixel) for the display, rendered from the
# DejaVu Sans TrueType fonts (Bitstream Vera license, https://dejavu-fonts.github.io/License.html).
#
# Usage: python3 scripts/genfonts.py > src/lcd/fonts.cpp
# Requires Pillow and the DejaVu fonts (Debian/Ubuntu: python3-pil, fonts-dejavu-core).
#

import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "/usr/share/fonts/truetype/dejavu/"

# Name, TrueType file, size in pixels
FONTS = [
	("FontSmall",  "DejaVuSans.ttf",      15),
	("FontMedium", "DejaVuSans-Bold.ttf", 19),
	("FontLarge",  "DejaVuSans-Bold.ttf", 28),
]

FIRST_CHAR = 32
LAST_CHAR  = 126


def render_font(name, filename, size, out):
	font = ImageFont.truetype(FONT_DIR + filename, size)
	ascent, descent = font.getmetrics()

	glyphs = []
	data = []

	for code in range(FIRST_CHAR, LAST_CHAR + 1):
		char = chr(code)
		advance = round(font.getlength(char))
		x0, y0, x1, y1 = font.getbbox(char, anchor="ls")
		width, height = max(x1 - x0, 0), max(y1 - y0, 0)

		offset = len(data)
		if width and height:
			image = Image.new("L", (width, height), 0)
			ImageDraw.Draw(image).text((-x0, -y0), char, font=font, fill=255, anchor="ls")
			pixels = image.load()

			# Rows of 4-bit alpha values, two pixels per byte, high nibble first
			for y in range(height):
				row = [min(15, (pixels[x, y] + 8) >> 4) for x in range(width)]
				if len(row) % 2:
					row.append(0)
				data += [row[i] << 4 | row[i + 1] for i in range(0, len(row), 2)]

		# Vertical offset from the top of the line
		glyphs.append((offset, width, height, x0, ascent + y0, advance))

	out.write(f"// {filename}, {size} pixels\n")
	out.write(f"static const u8 {name}Data[] =\n{{\n")
	for i in range(0, len(data), 16):
		out.write("\t" + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
	out.write("};\n\n")

	out.write(f"static const TUIGlyph {name}Glyphs[] =\n{{\n")
	for code, (offset, width, height, x, y, advance) in zip(range(FIRST_CHAR, LAST_CHAR + 1), glyphs):
		comment = chr(code).replace("\\", "backslash")
		out.write(f"\t{{ {offset:6d}, {width:3d}, {height:3d}, {x:3d}, {y:3d}, {advance:3d} }},\t// {comment}\n")
	out.write("};\n\n")

	out.write(f"const TUIFont {name} = {{ {ascent + descent}, {ascent}, {FIRST_CHAR}, {LAST_CHAR}, {name}Glyphs, {name}Data }};\n\n")


def main():
	out = sys.stdout
	out.write("//\n// fonts.cpp\n//\n")
	out.write("// Generated by scripts/genfonts.py from the DejaVu Sans fonts (Bitstream Vera license,\n")
	out.write("// https://dejavu-fonts.github.io/License.html). Do not edit.\n//\n\n")
	out.write("#include \"lcd/fonts.h\"\n\n")

	for name, filename, size in FONTS:
		render_font(name, filename, size, out)


if __name__ == "__main__":
	main()
