#!/usr/bin/env python3
#
# genlogo.py
#
# Generates src/lcd/logo.cpp: the "Troubadour" logo in blackletter, as anti-aliased images (4 bits per pixel), one
# for the illuminated initial and one for the rest of the word with an ornamental rule below it. The images have the
# same size, so that they can be drawn at the same position in different colours.
#
# The font is UnifrakturCook (SIL Open Font License, see fonts/UnifrakturCook-OFL.txt).
#
# Usage: python3 scripts/genlogo.py > src/lcd/logo.cpp
#        python3 scripts/genlogo.py --png <file> [<scale>]	(coloured PNG with a transparent background, <scale>
#                                                        	times the size on the display; default 4)
# Requires Pillow (Debian/Ubuntu: python3-pil).
#

import os
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFont

FONT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts", "UnifrakturCook-Bold.ttf")

NAME = "Troubadour"
WIDTH = 200
MAX_SIZE = 80
RULE_GAP = 4
RULE_HEIGHT = 2
DIAMOND = 5

# As in src/lcd/ui.cpp
COLOR_INITIAL = (205, 40, 35)
COLOR_TEXT = (230, 185, 85)


def fit_font(scale):
	# Largest size at which the word fits into the width
	for size in range(MAX_SIZE * scale, 8, -1):
		font = ImageFont.truetype(FONT, size)
		x0, _, x1, _ = font.getbbox(NAME, anchor="ls")
		if x1 - x0 <= WIDTH * scale:
			return font
	raise SystemExit("Logo doesn't fit")


def render(scale=1):
	font = fit_font(scale)
	x0, y0, x1, y1 = font.getbbox(NAME, anchor="ls")
	text_width, text_height = x1 - x0, y1 - y0
	rule_y = text_height + (RULE_GAP + DIAMOND) * scale

	height = rule_y + DIAMOND * scale + 1
	width = text_width

	initial = Image.new("L", (width, height), 0)
	rest = Image.new("L", (width, height), 0)

	# The initial, and the rest of the word after it
	ImageDraw.Draw(initial).text((-x0, -y0), NAME[0], font=font, fill=255, anchor="ls")
	ImageDraw.Draw(rest).text((-x0 + font.getlength(NAME[0]), -y0), NAME[1:], font=font, fill=255, anchor="ls")

	# Ornamental rule with a diamond in the middle, drawn at 4x and scaled down for smooth edges
	ss = 4
	big = Image.new("L", (width * ss, height * ss), 0)
	draw = ImageDraw.Draw(big)
	middle = width * ss // 2
	y = rule_y * ss
	margin = width * ss // 8
	r = RULE_HEIGHT * scale * ss // 2
	draw.rectangle((margin, y - r, width * ss - margin, y + r), fill=255)
	d = DIAMOND * scale * ss
	draw.polygon([(middle, y - d), (middle + d, y), (middle, y + d), (middle - d, y)], fill=255)
	for x in (margin, width * ss - margin):
		draw.polygon([(x, y - d // 2), (x + d // 2, y), (x, y + d // 2), (x - d // 2, y)], fill=255)
	ornament = big.resize((width, height), Image.LANCZOS)

	return width, height, initial, ImageChops.lighter(rest, ornament)


def write_image(out, name, image):
	width, height = image.size
	pixels = image.load()
	data = []

	# Rows of 4-bit alpha values, two pixels per byte, high nibble first
	for y in range(height):
		row = [min(15, (pixels[x, y] + 8) >> 4) for x in range(width)]
		if len(row) % 2:
			row.append(0)
		data += [row[i] << 4 | row[i + 1] for i in range(0, len(row), 2)]

	out.write(f"static const u8 {name}Data[] =\n{{\n")
	for i in range(0, len(data), 16):
		out.write("\t" + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
	out.write("};\n\n")
	out.write(f"const TUIImage {name} = {{ {width}, {height}, {name}Data }};\n\n")


def write_png(path, scale):
	width, height, initial, rest = render(scale)

	# Each layer in its colour, the initial on top
	image = Image.new("RGBA", (width, height), (0, 0, 0, 0))
	for color, alpha in ((COLOR_TEXT, rest), (COLOR_INITIAL, initial)):
		layer = Image.new("RGBA", (width, height), color + (0,))
		layer.putalpha(alpha)
		image = Image.alpha_composite(image, layer)

	image.save(path)


def main():
	if len(sys.argv) > 2 and sys.argv[1] == "--png":
		write_png(sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 4)
		return

	width, height, initial, rest = render()

	out = sys.stdout
	out.write("//\n// logo.cpp\n//\n")
	out.write("// Generated by scripts/genlogo.py from the UnifrakturCook font (SIL Open Font License,\n")
	out.write("// scripts/fonts/UnifrakturCook-OFL.txt). Do not edit.\n//\n\n")
	out.write("#include \"lcd/logo.h\"\n\n")
	write_image(out, "LogoInitial", initial)
	write_image(out, "LogoText", rest)


if __name__ == "__main__":
	main()
