#ifndef _fonts_h
#define _fonts_h

#include <circle/types.h>

// Anti-aliased bitmap fonts, generated by scripts/genfonts.py
struct TUIGlyph
{
	u32 nOffset;	// Into the font's data; rows of 4-bit alpha values, two pixels per byte, high nibble first
	u8 nWidth;
	u8 nHeight;
	s8 nOffsetX;	// From the pen position
	s8 nOffsetY;	// From the top of the line
	u8 nAdvance;
};

struct TUIFont
{
	u8 nHeight;	// Line height
	u8 nAscent;	// Top of the line to the baseline
	u8 nFirstChar;
	u8 nLastChar;
	const TUIGlyph* pGlyphs;
	const u8* pData;
};

extern const TUIFont FontTiny;
extern const TUIFont FontSmall;
extern const TUIFont FontMedium;
extern const TUIFont FontLarge;

// Symbols in the fonts, after the ASCII characters (as strings, to be put into text)
#define UI_SYMBOL_FLOPPY_DISK "\x7F"

#endif
